plot_state_qsphere(psi)

"""### 4. Unitary Simulation

The `unitary_simulator` calculates the 4x4 matrix that represents the *entire sequence of operations* in our circuit. This is useful for verifying the mathematical transformation performed by our gates.

**Important:** The resulting unitary matrix is for the composite operation `CX * (X ⊗ X)`, not just the CX gate alone.

**Expected Outcome:**
The simulator will output the 4x4 matrix equivalent to applying two X-gates followed by a CNOT gate. This matrix, when applied to the initial state vector for |00⟩ (which is `[1, 0, 0, 0]`), would produce the final state vector for |10⟩ (`[0, 0, 1, 0]`).
"""

backend = Aer.get_backend('unitary_simulator')

transpiled_qc = transpile(qc_cx, backend)

job = backend.run(transpiled_qc)

result = job.result()

unitary_matrix = result.get_unitary()

print("Unitary matrix of the circuit:")
print(np.round(unitary_matrix.data, 3))

"""### 5. Measurement Simulation with `qasm_simulator`

This simulation mimics a real quantum computer. We add measurement operations to our circuit and run it for a number of "shots" to get a statistical distribution of the outcomes.

- **`QuantumCircuit(2,2)`**: Creates a circuit with 2 qubits and 2 classical bits for storing measurement results.
- **`qc_cx.measure([0,1],[0,1])`**: Measures qubit 0 and maps the result to classical bit 0; measures qubit 1 and maps it to classical bit 1.
- **`Aer.get_backend('qasm_simulator')`**: Accesses the simulator that models measurement and noise.
- **`backend.run(..., shots=1000)`**: Executes the circuit 1000 times.
- **`result.get_counts()`**: Returns a dictionary of the measurement outcomes and how many times each occurred.
- **`plot_histogram(counts)`**: Displays the results as a bar chart.

**Expected Outcome:**
Since the final state |10⟩ is a computational basis state, there is no randomness. Every single one of the 1000 shots should yield the result `'10'`. The histogram will show a single bar at `'10'` with a probability of 1.0 (or a count of 1000).
"""

# CNOT with Measurement
qc_cx = QuantumCircuit(2,2,name="qc")
qc_cx.x(0) # X Gate on 1st Qubit
qc_cx.x(1) # X Gate on 2nd Qubit
qc_cx.cx(0,1) # CX Gate with 1st Qubit as Control and 2nd Qubit as Target
qc_cx.measure([0,1],[0,1])
qc_cx.draw('mpl')

backend = Aer.get_backend('qasm_simulator')

transpiled_qc = transpile(qc_cx, backend)

job = backend.run(transpiled_qc, shots=1000)

result = job.result()

counts = result.get_counts()
print("\nTotal counts are:", counts)

plot_histogram(counts)

"""### 6. Alternative CNOT Implementation: H-CZ-H

The CNOT gate can be constructed from other fundamental gates. A common identity is that a CX gate is equivalent to a CZ gate surrounded by Hadamard gates on the **target qubit**.

**Identity:** `CX(c, t) = (I ⊗ H_t) * CZ(c, t) * (I ⊗ H_t)`

Here, we build this equivalent circuit to demonstrate that it produces the exact same result. The `barrier()` calls are added for visual clarity in the circuit diagram and have no logical effect.

**Expected Outcome:**
The measurement results will be identical to the previous `qasm_simulator` run. The histogram will show 100% of the counts in the `'10'` state, proving that for the input |11⟩, this H-CZ-H construction is functionally identical to a native CX gate.
"""

# CNOT with Measurement
qc_cx = QuantumCircuit(2,2,name="qc")
qc_cx.x(0) # X Gate on 1st Qubit
qc_cx.x(1) # X Gate on 2nd Qubit
qc_cx.barrier()
qc_cx.h(1) # H Gate on 2nd Qubit
qc_cx.cz(0,1) # CZ Gate
qc_cx.h(1) # H Gate on 2nd Qubit
qc_cx.barrier()
qc_cx.measure([0,1],[0,1])
qc_cx.draw('mpl')

