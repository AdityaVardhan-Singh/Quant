# CX-gate on |11> = |10> (|01> according to Qiskit ordering)
qc_cx = QuantumCircuit(2,name="qc")
qc_cx.x(0) # X Gate on 1st Qubit
qc_cx.x(1) # X Gate on 2nd Qubit
qc_cx.cx(0,1) # CX Gate with 1st Qubit as Control and 2nd Qubit as Target
qc_cx.draw('mpl')

"""### 2. Statevector Simulation & Density Matrix Plot

To see the pure quantum state of the circuit *before* measurement, we use the `statevector_simulator`. This gives us the final statevector, a complex vector representing the amplitudes of each basis state.

- **`Aer.get_backend('statevector_simulator')`**: Accesses the ideal simulator that calculates the final statevector.
- **`result.get_statevector()`**: Extracts the statevector `psi` from the simulation results.
- **`plot_state_city(psi)`**: Creates a "cityscape" plot of the density matrix, which is a great way to visualize the magnitude and phase of the statevector's components.

**Expected Outcome:**
The output statevector should be `[0, 0, 1, 0]`. This corresponds to the basis states |00⟩, |01⟩, |10⟩, |11⟩, respectively. A `1` in the third position means the system is deterministically in the state |10⟩. The city plot will show a single, solid blue bar at the '10' position.
"""

simulator_state = Aer.get_backend('statevector_simulator')

job_state = transpile(qc_cx, simulator_state)

result_state = simulator_state.run(job_state).result()

psi  = result_state.get_statevector(qc_cx)
print("\nQuantum state is:",psi)

plot_state_city(psi)

"""### 3. Q-Sphere Visualization

The Q-sphere is another powerful tool for visualizing a multi-qubit state. It maps the amplitudes and phases of the basis states onto the surface of a sphere.

- **`plot_state_qsphere(psi)`**: Generates the Q-sphere plot from the statevector.

**Expected Outcome:**
You will see a single bright spot and a line pointing to the computational basis state corresponding to **|10⟩**, visually confirming our result. The size of the spot indicates the magnitude of the amplitude (100%), and its color represents the phase (0, or real and positive).
"""

# Plot the QSphere
